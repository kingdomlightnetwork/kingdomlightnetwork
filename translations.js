/* =====================================================
   GET TRANSLATION
===================================================== */

function getTranslation(
    key,
    language = currentLanguage
) {

    if (
        translations[language] &&
        translations[language][key] !== undefined
    ) {

        return translations[language][key];

    }


    if (
        translations.en &&
        translations.en[key] !== undefined
    ) {

        return translations.en[key];

    }


    return key;

}


/* =====================================================
   SET TRANSLATION LANGUAGE
===================================================== */

function setTranslationLanguage(
    language
) {

    if (
        !translations[language]
    ) {

        console.warn(
            "Language not found:",
            language
        );

        return;

    }


    currentLanguage =
        language;


    document.documentElement.lang =
        language;


    /* ---------------------------------------------
       RTL LANGUAGES
    --------------------------------------------- */

    if (
        language === "ur" ||
        language === "pa" ||
        language === "ar" ||
        language === "fa"
    ) {

        document.documentElement.dir =
            "rtl";

    } else {

        document.documentElement.dir =
            "ltr";

    }


    localStorage.setItem(
        "language",
        language
    );


    console.log(
        "Website language changed to:",
        language
    );

}


